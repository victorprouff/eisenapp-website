let currentLang = "en";

function detectLang() {
  const saved = localStorage.getItem("eisenapp-lang");
  if (saved && translations[saved]) return saved;
  const browser = (navigator.language || "en").slice(0, 2).toLowerCase();
  return translations[browser] ? browser : "en";
}

function applyTranslations(lang) {
  currentLang = lang;
  localStorage.setItem("eisenapp-lang", lang);
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = translations[lang][key];
    if (value !== undefined) el.innerHTML = value;
  });

  const select = document.querySelector(".lang-select");
  if (select) select.value = lang;
}

document.addEventListener("DOMContentLoaded", () => {
  applyTranslations(detectLang());

  const select = document.querySelector(".lang-select");
  if (select) select.addEventListener("change", () => applyTranslations(select.value));

  // Download modal
  const modal = document.getElementById("download-modal");
  const modalClose = document.getElementById("modal-close");
  const modalDownload = document.getElementById("modal-download");
  let pendingUrl = null;
  let lastFocused = null;

  function getFocusable() {
    return Array.from(modal.querySelectorAll('a[href], button:not([disabled])'));
  }

  function trapFocus(e) {
    if (e.key !== "Tab") return;
    const focusable = getFocusable();
    const first = focusable[0];
    const last = focusable[focusable.length - 1];
    if (e.shiftKey) {
      if (document.activeElement === first) { e.preventDefault(); last.focus(); }
    } else {
      if (document.activeElement === last) { e.preventDefault(); first.focus(); }
    }
  }

  function openModal(url) {
    pendingUrl = url;
    lastFocused = document.activeElement;
    modal.classList.add("is-open");
    modal.setAttribute("aria-hidden", "false");
    modal.addEventListener("keydown", trapFocus);
    modalClose.focus();
  }

  function closeModal() {
    modal.classList.remove("is-open");
    modal.setAttribute("aria-hidden", "true");
    modal.removeEventListener("keydown", trapFocus);
    pendingUrl = null;
    if (lastFocused) lastFocused.focus();
  }

  document.querySelectorAll(".platform-card").forEach((card) => {
    card.addEventListener("click", (e) => {
      e.preventDefault();
      openModal(card.href);
    });
  });

  modalClose.addEventListener("click", closeModal);

  modal.addEventListener("click", (e) => {
    if (e.target === modal) closeModal();
  });

  modalDownload.addEventListener("click", () => {
    if (pendingUrl) window.open(pendingUrl, "_blank", "noopener");
    closeModal();
  });

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && modal.classList.contains("is-open")) closeModal();
  });
});
